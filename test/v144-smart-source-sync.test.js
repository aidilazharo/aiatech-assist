test('approved source revision yields UPDATE on the SAME Jira keys, not duplicate CREATE or DELETE',()=>fixture(async({registry})=>{
 let r=await workflow.load(registry,'cockpit');
 r=await workflow.imported(registry,'cockpit',r.revision,{name:'base.docx',digest:'a'.repeat(64)});
 r=await workflow.discoverySaved(registry,'cockpit',r.revision,'rev-1');
 r=await workflow.reviewed(registry,'cockpit',r.revision,{discoveryRevision:'rev-1',text:'Reviewed'});
 r=await workflow.generated(registry,'cockpit',r.revision,{discoveryRevision:'rev-1',requirements:[req()]});
 r=await workflow.edit(registry,'cockpit',r.revision,{brId:'BR-001',content:req()});
 r=await workflow.approve(registry,'cockpit',r.revision,{brId:'BR-001'});
 const original=workflow.plan(r);const ids=original.map(x=>x.path);
 for(const item of original){r=await workflow.recorded(registry,'cockpit',r.revision,{path:item.path,action:'create',key:'TC-'+(300+ids.indexOf(item.path)),hash:item.hash,kind:item.kind,title:item.title,remoteDigest:'a'.repeat(64)});}
 assert.deepEqual(workflow.plan(r),[]);
 const unchangedKeys=Object.fromEntries(Object.entries(r.synced).map(([k,v])=>[k,v.key]));
 r=await workflow.write(registry,'cockpit',r.revision,n=>{n.importEpoch++;n.discoveryRevision='rev-2';n.reviewRevision='rev-2';n.reviewText='Reviewed revision';});
 const changed={...req(),id:'BR-001',scope:'Include extra special routing, mobile and website clients'};
 r=await workflow.generated(registry,'cockpit',r.revision,{discoveryRevision:'rev-2',requirements:[changed]});
 assert.equal(workflow.plan(r).length,0,'unapproved draft must never update Jira');
 r=await workflow.edit(registry,'cockpit',r.revision,{brId:'BR-001',content:changed});
 r=await workflow.approve(registry,'cockpit',r.revision,{brId:'BR-001'});
 const changes=workflow.plan(r);
 assert.equal(changes.length,1);
 assert.equal(changes[0].action,'update');
 assert.equal(changes[0].path,'BR-001');
 assert.equal(changes[0].key,unchangedKeys['BR-001']);
 assert.equal(changes.filter(x=>x.action==='create'||x.action==='retire').length,0);
 assert.deepEqual(Object.fromEntries(Object.entries(r.synced).map(([k,v])=>[k,v.key])),unchangedKeys);
}));
