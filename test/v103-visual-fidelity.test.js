'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const tab=require('../src/design-tab');
const artifacts=require('../src/design-artifacts');
const proposals=require('../src/design-proposals');
const host=fs.readFileSync(path.join(__dirname,'..','test','generated','extension-source.txt'),'utf8');
const dashboard=fs.readFileSync(path.join(__dirname,'..','media','start.js'),'utf8');
const design={title:'<script>unsafe</script>',summary:'For review',screens:[{name:'Dashboard',purpose:'Overview',components:['Search field','Save button'],interactions:['Save']},{name:'Details',purpose:'Details',components:['Edit button'],interactions:['Continue']}],flows:['Dashboard to Details'],assumptions:[],questions:[]};
const api={title:'Customer API',summary:'Review',endpoints:[{method:'POST',path:'/customers',operation:'Create customer',authorization:'Bearer',request:'Name',response:'Created',responseSchema:{type:'object',properties:{id:{type:'integer'},message:{type:'string',example:'created'}}}}],assumptions:[],questions:[]};
const diagram={title:'Flow',nodes:[{id:'a',label:'User',x:15,y:20,width:200,height:90},{id:'b',label:'API',x:290,y:20,width:220,height:90}],edges:[{from:'a',to:'b',label:'Calls'}]};
function render(kind,body,standalone=false){return tab.render({item:{id:'p1',actor:'Design Owner',at:'2026-10-31T01:30:00Z',aiModel:'Selected AI',sourceHash:'source',status:'draft',number:1,design:body},kind,isLatest:true,approvedHash:'source',nonce:'safe',standalone});}
test('all design previews compile executable scripts safely and browser mode has no extension bridge dependency',()=>{
 for(const [kind,body] of Object.entries({design,ux:design,mockup:design,architecture:{...design,diagram},api,database:{...design,entities:[{name:'customers',description:'Customer',fields:[{name:'id',type:'UUID',key:true,required:true}],relationships:[]}]}})){
  for(const standalone of [false,true]){
   const html=render(kind,body,standalone),script=html.match(/<script nonce="safe">([\s\S]*?)<\/script>/)?.[1];
   assert.ok(script,kind);assert.doesNotThrow(()=>new vm.Script(script),kind);
   assert.doesNotMatch(html,/<script>unsafe<\/script>/);
   assert.match(html,/Generated by/);assert.match(html,/Design Owner/);assert.match(html,/Selected AI/);
   if(standalone)assert.doesNotMatch(script,/const vscode=acquireVsCodeApi\(\)/);
   else assert.match(script,/const vscode=acquireVsCodeApi\(\)/);
  }
 }
});
test('API viewer has Swagger-inspired operation cards and local response testing with explicit simulated result',()=>{
 const html=render('api',api);
 assert.match(html,/OPENAPI 3\.1/);assert.match(html,/data-api-index="0"/);
 assert.match(html,/SIMULATED RESPONSE/);assert.match(html,/No HTTP request was sent/);
 assert.match(html,/201 Created/);assert.match(html,/created/);
});
test('diagrams have draggable SVG node controls and draft-only save positions',()=>{
 const html=render('architecture',{...design,diagram});assert.match(html,/data-node-id="a"/);
 assert.match(html,/pointermove/);assert.match(html,/saveLayout/);assert.match(html,/canSaveLayout=true/);
 assert.match(html,/designEditStructured/);
});
test('Screen Mockups is the only new screen-design choice and its export is interactive',()=>{
 assert.ok(!dashboard.includes("['prototype','Interactive UI Prototype']"));
 assert.ok(dashboard.includes("['mockup','Screen Mockups']"));
 const output=artifacts.outputFiles('mockup',design);
 assert.match(output['screen-mockups.html'],/data-screen="1"/);
 assert.match(output['screen-mockups.html'],/simulated; no data is saved/);
 assert.match(proposals.prompt('mockup',{entries:[{title:'Approval'}]}),/connected clickable screen journeys/);
});
test('only Screen Mockups can open externally; other designs remain in the ATGV pane with AI metadata',()=>{
 assert.doesNotMatch(host,/case 'designOpenVisualBrowser':/);
 assert.match(host,/case 'designOpenMockupBrowser':/);
 assert.match(host,/msg.kind!=='mockup'/);
 assert.doesNotMatch(host,/vscode\.ViewColumn\.Two/);
 assert.doesNotMatch(host,/editorLayoutTwoColumns/);
 assert.match(dashboard,/design-preview-open/);
 assert.match(dashboard,/Open Full Website in Browser/);
 assert.match(host,/aiModel:target\.label/);
 assert.match(proposals.add.toString(),/aiModel/);
});
