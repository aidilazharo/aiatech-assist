test('all BA uploads preserve current approved discovery until selected for processing',()=>project(async registry=>{
 let state=await br.load(registry,'sample');
 const first=document('policy.pdf','Document 1 content');
 state=await br.addSources(registry,'sample',state.revision,[first]);
 assert.equal(state.importEpoch,0);
 assert.deepEqual(state.processedSources,null);
 assert.equal(state.sourceDocuments[0].uploadedBy,'Alice');
 state=await br.selectSources(registry,'sample',state.revision,[first.digest]);
 assert.deepEqual(state.processedSources,[first.digest]);
 assert.equal(state.importEpoch,1);
 state=await br.discoverySaved(registry,'sample',state.revision,'R1');
 state=await br.reviewed(registry,'sample',state.revision,{discoveryRevision:'R1',text:JSON.stringify({readiness:'Ready',suggestions:[]})});
 const extra=document('claims.pdf','Document 2 content','Bob');
 state=await br.addSources(registry,'sample',state.revision,[first,extra]);
 assert.equal(state.reviewRevision,'R1');
 assert.equal(state.discoveryRevision,'R1');
 assert.deepEqual(state.processedSources,[first.digest]);
 assert.equal(state.sourceDocuments[1].uploadedBy,'Bob');
 assert.equal(state.importEpoch,1);
}));
test('source selection rejects empty, duplicate and stale document selections',()=>project(async registry=>{
 let state=await br.load(registry,'sample');
 const one=document('one.pdf','One unique document'),two=document('two.pdf','Two unique document');
 state=await br.addSources(registry,'sample',state.revision,[one,two]);
 await assert.rejects(br.selectSources(registry,'sample',state.revision,[]),/Select 1–10/);
 await assert.rejects(br.selectSources(registry,'sample',state.revision,[one.digest,one.digest]),/unique/);
 await assert.rejects(br.selectSources(registry,'sample',state.revision,[sha('missing')]),/changed/);
 await assert.rejects(br.selectSources(registry,'sample','stale',[one.digest]),/changed/);
 state=await br.selectSources(registry,'sample',state.revision,[two.digest]);
 assert.deepEqual(state.processedSources,[two.digest]);
 assert.equal(state.importName,'two.pdf');
}));
test('replacing a processed source forces remapping, while unselected changes do not',()=>project(async registry=>{
 let state=await br.load(registry,'sample');
 const first=document('a.pdf','Processed first document'),second=document('b.pdf','Unprocessed second document');
 state=await br.addSources(registry,'sample',state.revision,[first,second]);
 state=await br.selectSources(registry,'sample',state.revision,[first.digest]);
 state=await br.discoverySaved(registry,'sample',state.revision,'R1');
 state=await br.reviewed(registry,'sample',state.revision,{discoveryRevision:'R1',text:JSON.stringify({readiness:'Ready',suggestions:[]})});
 state=await br.addSources(registry,'sample',state.revision,[first,document('b.pdf','Edited unprocessed document')]);
 assert.equal(state.reviewRevision,'R1');
 state=await br.addSources(registry,'sample',state.revision,[document('a.pdf','Edited processed document'),second]);
 assert.deepEqual(state.processedSources,[]);
 assert.equal(state.reviewRevision,'');
}));
test('source files are stored under their project and verified against content digests',()=>project(async(registry,home)=>{
 const file=path.join(home,'source.pdf');
 await fs.writeFile(file,'%PDF-1.4\n1 0 obj\n<< /Length 90 >>\nstream\n(This is a business requirement with enough text for extraction.) Tj\nendstream\nendobj');
 const {importDocumentText}=require('../src/discovery-import');
 const parsed=await importDocumentText(file),entry={...parsed,digest:sha(parsed.text)};
 entry.storedName=await store.store(registry,'sample',entry,file);
 assert.match(entry.storedName,/^[a-f0-9]{64}\.pdf$/);
 const result=await store.read(registry,'sample',entry);
 assert.equal(result.text,parsed.text);
 const storageFile=path.join(store.sourceDirectory(registry,'sample'),entry.storedName);
 assert.ok((await fs.stat(storageFile)).isFile());
 await fs.writeFile(storageFile,'%PDF-1.4\nstream\n(Tampered document cannot be mapped.) Tj\nendstream');
 await assert.rejects(store.read(registry,'sample',entry),/changed/);
 await assert.rejects(store.read(registry,'sample',{...entry,storedName:'../../unsafe.pdf'}),/uploaded before|Re-upload/);
}));
